import type { RouteSpec } from "@hostpanel/shared";
import { decrypt, env } from "./env.js";
import { run } from "./exec.js";
import { writeFileAtomic } from "./fsx.js";
import { phpSocket } from "./runtime.js";

/**
 * Builds the whole Caddyfile from the routing table. Every value inserted here was
 * validated by validate.ts (hostnames, absolute paths and URLs from a safe character
 * set), so nothing can break out of its directive.
 */
export const certPath = (hostname: string) => `/etc/caddy/certs/${hostname.replace(/^\*\./, "_wildcard.")}`;

export function buildCaddyfile(routes: RouteSpec[], panelHostname: string | null, acmeEmail: string | null, dnsToken: string | null = null): string {
  if (dnsToken !== null && !/^[A-Za-z0-9_-]{20,200}$/.test(dnsToken)) throw new Error("DNS API token has unexpected characters");
  const out: string[] = [];
  out.push(`# Generated by HostPanel agent at ${new Date().toISOString()}. Do not edit: changes are overwritten.
{
\tadmin localhost:2019${acmeEmail ? `\n\temail ${acmeEmail}` : ""}
\tservers {
\t\ttimeouts {
\t\t\tread_header 15s
\t\t\tidle 2m
\t\t}
\t}
}

(hp_common) {
\tencode zstd gzip
\theader {
\t\tX-Content-Type-Options nosniff
\t\tReferrer-Policy strict-origin-when-cross-origin
\t\t-Server
\t}
\t@hp_hidden path /.git /.git/* /.env /.env.* /.htaccess /.user.ini /composer.lock
\trespond @hp_hidden 404
}
`);

  if (panelHostname) {
    out.push(`${panelHostname} {
\tencode zstd gzip
\treverse_proxy ${env.panelUpstream}
}
`);
  }

  for (const r of routes) {
    const logDir = `/home/${r.linuxUser}/sites/${r.siteName}/logs`;
    const log = `\tlog {
\t\toutput file ${logDir}/access.log {
\t\t\troll_size 20MiB
\t\t\troll_keep 5
\t\t}
\t}`;
    const tlsLine = (route: RouteSpec): string => {
      if (route.tls === "dns") {
        if (!dnsToken) throw new Error(`${route.hostname} needs a DNS-issued certificate but no DNS provider token is set`);
        return `\ttls {\n\t\tdns cloudflare ${dnsToken}\n\t}\n`;
      }
      if (route.tls) return `\ttls ${certPath(route.hostname)}.crt ${certPath(route.hostname)}.key\n`;
      return "";
    };
    if (r.kind === "redirect") {
      out.push(`${r.hostname} {
${tlsLine(r)}\tredir ${r.redirectTo!.replace(/\/$/, "")}{uri} ${r.redirectCode ?? 301}
}
`);
      continue;
    }
    const proxy = (port: number, instances: number, indent: string) =>
      `${indent}reverse_proxy ${Array.from({ length: instances }, (_, i) => `127.0.0.1:${port + i}`).join(" ")} {
${indent}\tlb_policy round_robin
${indent}\tlb_try_duration 5s
${indent}\tfail_duration 10s
${indent}}`;

    // The site's own handling, indented one level deeper when path rules wrap it in `handle {}`.
    const ind = r.paths?.length ? "\t\t" : "\t";
    let main: string;
    switch (r.kind) {
      case "php":
        main = `${ind}root * ${r.root}
${ind}php_fastcgi unix/${phpSocket(r.linuxUser, r.siteName)}
${ind}file_server`;
        break;
      case "proxy":
        main = proxy(r.port!, r.instances ?? 1, ind);
        break;
      default:
        main = `${ind}root * ${r.root}
${ind}try_files {path} {path}/ {path}.html
${ind}file_server`;
    }
    const pathBlocks = (r.paths ?? []).map((p) => `\thandle ${p.path} {
${proxy(p.port, p.instances, "\t\t")}
\t}`);
    const body = pathBlocks.length ? `${pathBlocks.join("\n")}\n\thandle {\n${main}\n\t}` : main;
    out.push(`${r.hostname} {
${tlsLine(r)}\timport hp_common
${log}
${body}
}
`);
  }
  return out.join("\n");
}

/** Writes uploaded certificates where Caddy can read them (root:caddy 0640). */
export async function writeCustomCerts(routes: RouteSpec[]): Promise<void> {
  for (const r of routes) {
    if (!r.tls || r.tls === "dns") continue;
    const cert = decrypt(r.tls.certEnc);
    const key = decrypt(r.tls.keyEnc);
    if (!cert.includes("-----BEGIN CERTIFICATE-----") || !/-----BEGIN (RSA |EC )?PRIVATE KEY-----/.test(key)) throw new Error(`Bad certificate for ${r.hostname}`);
    await writeFileAtomic(`${certPath(r.hostname)}.crt`, cert, 0o640);
    await writeFileAtomic(`${certPath(r.hostname)}.key`, key, 0o640);
    await run("chgrp", [env.webUser, `${certPath(r.hostname)}.crt`, `${certPath(r.hostname)}.key`], { allowFail: true });
  }
}

/** Writes the Caddyfile and asks Caddy to load it (zero-downtime, keeps certificates). */
export async function applyCaddyfile(content: string): Promise<void> {
  // 0640 root:caddy because it may contain the DNS API token
  await writeFileAtomic(env.caddyfile, content, 0o640);
  await run("chgrp", [env.webUser, env.caddyfile], { allowFail: true });
  if (env.dryRun) {
    console.log(`[dry-run] POST ${env.caddyAdmin}/load (${content.length} bytes)`);
    return;
  }
  const res = await fetch(`${env.caddyAdmin}/load`, {
    method: "POST",
    headers: { "Content-Type": "text/caddyfile" },
    body: content,
  });
  if (!res.ok) {
    const text = await res.text().catch(() => "");
    throw new Error(`Caddy rejected the config (${res.status}): ${text.slice(0, 800)}`);
  }
}
