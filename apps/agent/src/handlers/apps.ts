/**
 * One-click apps. Everything that runs the app's own tooling (curl, composer, npm, pip, wp-cli)
 * runs as the customer's Linux user inside their resource limits, in a fresh release folder
 * that only goes live once it passes the health check, exactly like a deploy.
 */

const sq = (v: string) => `'${v.replace(/'/g, `'\\''`)}'`; // single-quote for bash

function stamp(d = new Date()): string {
  const p = (n: number) => String(n).padStart(2, "0");
  return `${d.getUTCFullYear()}${p(d.getUTCMonth() + 1)}${p(d.getUTCDate())}-${p(d.getUTCHours())}${p(d.getUTCMinutes())}${p(d.getUTCSeconds())}`;
}

interface Plan {
  script: string;
  env?: Record<string, string>;
  files?: { path: string; content: string; mode?: number }[];
  adminUrl: string;
  notes: string[];
}

function plan(p: JobPayloads["app.install"], dir: string, db: { name: string; user: string; password: string } | null, admin: { user: string; email: string; password: string } | null): Plan {
  const url = `https://${p.domain}`;
  switch (p.template) {
    case "wordpress": {
      const salt = () => randomBytes(48).toString("base64").replace(/[^A-Za-z0-9]/g, "").slice(0, 64);
      const keys = ["AUTH_KEY", "SECURE_AUTH_KEY", "LOGGED_IN_KEY", "NONCE_KEY", "AUTH_SALT", "SECURE_AUTH_SALT", "LOGGED_IN_SALT", "NONCE_SALT"];
      return {
        files: [
          {
            path: `${dir}/wp-config.php`,
            mode: 0o640,
            content: `<?php
// Generated by HostPanel
define('DB_NAME', '${db!.name}');
define('DB_USER', '${db!.user}');
define('DB_PASSWORD', '${db!.password}');
define('DB_HOST', '127.0.0.1');
define('DB_CHARSET', 'utf8mb4');
define('DB_COLLATE', '');
${keys.map((k) => `define('${k}', '${salt()}');`).join("\n")}
$table_prefix = 'wp_';
define('WP_DEBUG', false);
define('FS_METHOD', 'direct');
define('DISALLOW_FILE_EDIT', true);
if (isset($_SERVER['HTTP_X_FORWARDED_PROTO']) && $_SERVER['HTTP_X_FORWARDED_PROTO'] === 'https') { $_SERVER['HTTPS'] = 'on'; }
if (!defined('ABSPATH')) { define('ABSPATH', __DIR__ . '/'); }
require_once ABSPATH . 'wp-settings.php';
`,
          },
        ],
        script: `set -e
echo "Downloading WordPress"
curl -fsSL https://wordpress.org/latest.tar.gz | tar -xz --strip-components=1 --exclude=wp-config-sample.php
echo "Downloading WP-CLI"
curl -fsSL -o /tmp/wp-cli.phar https://raw.githubusercontent.com/wp-cli/builds/gh-pages/phar/wp-cli.phar
php /tmp/wp-cli.phar core install --url=${sq(url)} --title="$APP_TITLE" --admin_user="$APP_ADMIN_USER" --admin_password="$APP_ADMIN_PASSWORD" --admin_email="$APP_ADMIN_EMAIL" --skip-email
php /tmp/wp-cli.phar rewrite structure '/%postname%/' --hard || true
rm -f /tmp/wp-cli.phar`,
        adminUrl: `${url}/wp-admin/`,
        notes: [`Log in at ${url}/wp-admin/ with the admin user below.`, "Permalinks are set to /%postname%/."],
      };
    }
    case "laravel":
      return {
        script: `set -e
echo "Creating a new Laravel project (composer create-project)"
composer create-project laravel/laravel . --no-interaction --prefer-dist --no-progress
sed -i -e "s|^APP_URL=.*|APP_URL=${url}|" -e "s|^APP_ENV=.*|APP_ENV=production|" -e "s|^APP_DEBUG=.*|APP_DEBUG=false|" .env
sed -i -E "s|^#? ?DB_CONNECTION=.*|DB_CONNECTION=mysql|; s|^#? ?DB_HOST=.*|DB_HOST=127.0.0.1|; s|^#? ?DB_PORT=.*|DB_PORT=3306|; s|^#? ?DB_DATABASE=.*|DB_DATABASE=$APP_DB_NAME|; s|^#? ?DB_USERNAME=.*|DB_USERNAME=$APP_DB_USER|; s|^#? ?DB_PASSWORD=.*|DB_PASSWORD=$APP_DB_PASSWORD|" .env
php artisan key:generate --force
php artisan migrate --force
php artisan config:cache`,
        adminUrl: url,
        notes: ["The project is in the site's current release. Push it to GitHub and connect the repo to keep deploying.", "Database settings are in .env."],
      };
    case "nextjs":
      return {
        script: `set -e
echo "Creating a Next.js app (create-next-app)"
npx --yes create-next-app@latest . --ts --eslint --app --src-dir --use-npm --no-tailwind --no-turbopack --import-alias "@/*" --yes
npm run build`,
        adminUrl: url,
        notes: ["Edit src/app/page.tsx, or connect a GitHub repo to deploy your own code."],
      };
    case "django":
      return {
        script: `set -e
echo "Creating a Python virtualenv and a Django project"
python -m venv .venv
.venv/bin/pip install --quiet --upgrade pip
.venv/bin/pip install --quiet django gunicorn whitenoise
.venv/bin/django-admin startproject mysite .
cat >> mysite/settings.py <<'PY'

# ---- HostPanel ----
import os as _os
DEBUG = False
ALLOWED_HOSTS = [h for h in _os.environ.get("APP_DOMAINS", "").split(",") if h] or ["localhost"]
CSRF_TRUSTED_ORIGINS = ["https://" + h for h in ALLOWED_HOSTS]
SECURE_PROXY_SSL_HEADER = ("HTTP_X_FORWARDED_PROTO", "https")
STATIC_ROOT = BASE_DIR / "staticfiles"
MIDDLEWARE.insert(1, "whitenoise.middleware.WhiteNoiseMiddleware")
PY
.venv/bin/python manage.py migrate --noinput
DJANGO_SUPERUSER_PASSWORD="$APP_ADMIN_PASSWORD" .venv/bin/python manage.py createsuperuser --noinput --username "$APP_ADMIN_USER" --email "$APP_ADMIN_EMAIL"
.venv/bin/python manage.py collectstatic --noinput`,
        adminUrl: `${url}/admin/`,
        notes: [`Django admin: ${url}/admin/`, "Add APP_DOMAINS (comma-separated) in Environment if you add more domains."],
      };
  }
}

export async function appInstall(p: JobPayloads["app.install"], job: Job): Promise<DeployResult & { adminUrl: string; notes: string[] }> {
  const site: SiteSpec = p.site;
  const log = await openLog(p.deploymentId);
  const progress = (pct: number, message: string) => {
    log.line(message);
    return job.updateProgress({ pct, message });
  };
  try {
    await progress(5, "Preparing site folders and runtime");
    await siteProvision({ site });

    let db: { name: string; user: string; password: string } | null = null;
    if (p.db) {
      await progress(10, `Creating ${p.db.engine} database ${p.db.name}`);
      await dbCreate(p.db);
      db = { name: p.db.name, user: p.db.user, password: decrypt(p.db.passwordEnc) };
    }
    const admin = p.admin ? { user: p.admin.user, email: p.admin.email, password: decrypt(p.admin.passwordEnc) } : null;

    const releaseName = `${stamp()}-${p.template.slice(0, 12)}`;
    const releaseDir = `${paths.releases(site.linuxUser, site.name)}/${releaseName}`;
    await mkdir(sys(releaseDir), { recursive: true });
    const pl = plan(p, releaseDir, db, admin);
    for (const f of pl.files ?? []) await writeFileAtomic(f.path, f.content, f.mode ?? 0o644); // writeFileAtomic maps into the sandbox itself
    await run("chown", ["-R", `${site.linuxUser}:${site.linuxUser}`, releaseDir]);

    await progress(20, `Installing ${p.template} (this can take a few minutes)`);
    await runAsUser(site.linuxUser, pl.script, {
      cwd: sys(releaseDir),
      env: {
        ...decryptEnv(site),
        PATH: runtimePath(site),
        HOME: env.dryRun ? sys(`/home/${site.linuxUser}`) : `/home/${site.linuxUser}`,
        COMPOSER_HOME: `/home/${site.linuxUser}/.composer`,
        npm_config_cache: `/home/${site.linuxUser}/.npm`,
        CI: "true",
        NEXT_TELEMETRY_DISABLED: "1",
        APP_TITLE: p.domain,
        APP_DOMAINS: p.domain,
        ...(admin ? { APP_ADMIN_USER: admin.user, APP_ADMIN_EMAIL: admin.email, APP_ADMIN_PASSWORD: admin.password } : {}),
        ...(db ? { APP_DB_NAME: db.name, APP_DB_USER: db.user, APP_DB_PASSWORD: db.password } : {}),
      },
      log: log.stream,
      timeoutSec: 1800,
    });
    await run("setfacl", ["-R", "-m", `u:${env.webUser}:rX`, releaseDir]);

    const previous = await readLink(paths.current(site.linuxUser, site.name));
    await swapSymlink(releaseDir, paths.current(site.linuxUser, site.name));
    await progress(85, `Switched to release ${releaseName}`);
    await restartApp(site, log);
    if (!(await healthCheck(site, log))) {
      if (previous) await swapSymlink(previous, paths.current(site.linuxUser, site.name));
      throw new Error("The app was installed but did not answer the health check; see the log above");
    }
    await progress(100, `Installed. ${pl.notes.join(" ")}`);
    return { releaseName, commitSha: "", commitMessage: `One-click install: ${p.template}`, rolledBack: false, adminUrl: pl.adminUrl, notes: pl.notes };
  } catch (e) {
    log.line(`FAILED: ${(e as Error).message}`);
    throw e;
  } finally {
    await log.close();
  }
}
